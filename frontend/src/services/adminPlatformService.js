import api from "./api.js";

const get = (url, params) => api.get(url, { params }).then((r) => r.data);
export const getMetrics = () => get("/admin/metrics");
export const getUserDetail = (id) => get(`/admin/users/${id}`);
export const changeUserRole = (id, role) => api.post(`/admin/users/${id}/role`, { role }).then((r) => r.data);
export const suspendUser = (id, reason) => api.post(`/admin/users/${id}/suspend`, { reason }).then((r) => r.data);
export const getUserPoints = (id, params) => get(`/admin/users/${id}/points`, params);
export const getAudit = (params) => get("/admin/audit", params);
export const getRoomReports = (params) => get("/admin/room-reports", params);
export const resolveRoomReport = (id, action) => api.post(`/admin/room-reports/${id}/resolve`, { action }).then((r) => r.data);
export const getAdminRooms = (params) => get("/admin/rooms", params);
export const deleteAdminRoom = (id) => api.delete(`/admin/rooms/${id}`).then((r) => r.data);
export const getTopEarners = (hours) => get("/admin/points/top", { hours });
export const reversePoints = (key, reason) => api.post("/admin/points/reverse", { key, reason }).then((r) => r.data);
export const getAnnouncements = (params) => get("/admin/announcements", params);
export const createAnnouncement = (data) => api.post("/admin/announcements", data).then((r) => r.data.announcement);
export const updateAnnouncement = (id, data) => api.put(`/admin/announcements/${id}`, data).then((r) => r.data.announcement);
export const publishAnnouncement = (id) => api.post(`/admin/announcements/${id}/publish`).then((r) => r.data);
export const archiveAnnouncement = (id) => api.post(`/admin/announcements/${id}/archive`).then((r) => r.data);
export const getAdminSettings = () => get("/admin/settings");
export const updateAdminSettings = (patch) => api.put("/admin/settings", patch).then((r) => r.data);
export const getSubscriptionConfig = () => get("/admin/subscriptions");
export const saveSubscriptionConfig = (cfg) => api.put("/admin/subscriptions", cfg).then((r) => r.data);
export const getAdminPayments = (params) => get("/admin/payments", params);
export const getPaymentSummary = () => get("/admin/payments/summary");
export const revokeEntitlement = (id, reason) => api.post(`/admin/entitlements/${id}/revoke`, { reason }).then((r) => r.data);
export const getActiveAnnouncements = () => get("/announcements/active").then((r) => r.announcements);
export const updateUserDetails = (id, data) => api.put(`/admin/users/${id}`, data).then((r) => r.data);
